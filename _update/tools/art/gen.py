W=16
def blank(w=W,h=W): return [['.']*w for _ in range(h)]
def put(g,x,y,c):
    if 0<=y<len(g) and 0<=x<len(g[0]): g[y][x]=c
def rect(g,x0,y0,x1,y1,c):
    for y in range(y0,y1+1):
        for x in range(x0,x1+1): put(g,x,y,c)
def frame(g,x0,y0,x1,y1,edge='k',fill=None):
    if fill: rect(g,x0,y0,x1,y1,fill)
    for x in range(x0,x1+1): put(g,x,y0,edge); put(g,x,y1,edge)
    for y in range(y0,y1+1): put(g,x0,y,edge); put(g,x1,y,edge)
def disc(g,cx,cy,r,c):
    for y in range(int(cy-r-1),int(cy+r+2)):
        for x in range(int(cx-r-1),int(cx+r+2)):
            if (x-cx)**2+(y-cy)**2<=r*r+0.3: put(g,x,y,c)
def ring(g,cx,cy,r,c,t=0.9):
    for y in range(int(cy-r-2),int(cy+r+3)):
        for x in range(int(cx-r-2),int(cx+r+3)):
            d=math.hypot(x-cx,y-cy)
            if abs(d-r)<=t: put(g,x,y,c)
def line(g,x0,y0,x1,y1,c):
    n=max(abs(x1-x0),abs(y1-y0),1)
    for i in range(n+1): put(g,round(x0+(x1-x0)*i/n),round(y0+(y1-y0)*i/n),c)
def outline(g,edge='k'):
    h=len(g); w=len(g[0]); out=[r[:] for r in g]
    for y in range(h):
        for x in range(w):
            if g[y][x]=='.':
                for dx,dy in((1,0),(-1,0),(0,1),(0,-1)):
                    nx,ny=x+dx,y+dy
                    if 0<=nx<w and 0<=ny<h and g[ny][nx] not in ('.',edge): out[y][x]=edge;break
    return out
